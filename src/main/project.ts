/** Dev-only profiles Camel Studio runs with. They are never active in a normal build. */
export const PROFILE = 'camel-studio'
export const PROFILE_DEBUG = 'camel-studio-debug'

export const hasProfile = (pom: string, id: string): boolean => new RegExp(`<id>\\s*${id}\\s*</id>`).test(pom)

export function activeByDefaultProfiles(pom: string): string[] {
  const ids: string[] = []
  for (const block of pom.match(/<profile>[\s\S]*?<\/profile>/g) ?? []) {
    if (!/<activeByDefault>\s*true\s*<\/activeByDefault>/.test(block)) continue
    const id = block.match(/<id>\s*([^<\s]+)\s*<\/id>/)?.[1]
    if (id) ids.push(id)
  }
  return ids
}

function profilesXml(indent: string, unit: string, nl: string, version: string | null): string {
  const dep = (artifactId: string, i: string): string[] => [
    `${i}<dependency>`,
    `${i}${unit}<groupId>org.apache.camel.springboot</groupId>`,
    `${i}${unit}<artifactId>${artifactId}</artifactId>`,
    ...(version ? [`${i}${unit}<version>${version}</version>`] : []),
    `${i}</dependency>`
  ]
  const profile = (id: string, comment: string, ...artifactIds: string[]): string[] => [
    `${indent}<!-- ${comment} -->`,
    `${indent}<profile>`,
    `${indent}${unit}<id>${id}</id>`,
    `${indent}${unit}<dependencies>`,
    ...artifactIds.flatMap((a) => dep(a, indent + unit + unit)),
    `${indent}${unit}</dependencies>`,
    `${indent}</profile>`
  ]
  return [
    ...profile(PROFILE, 'Camel Studio: live statistics, tracing and test messages while running from the IDE. Not part of normal builds.', 'camel-cli-connector-starter'),
    // seda carries test messages into a route asynchronously, so one that stops at a breakpoint does not block the tooling.
    ...profile(PROFILE_DEBUG, 'Camel Studio: breakpoints and stepping. Only used by Debug in the IDE.', 'camel-debug-starter', 'camel-seda-starter')
  ].join(nl)
}

/** Adds the two Camel Studio profiles to pom.xml. Does nothing if they are already there. */
export async function enableRuntimeTools(root: string): Promise<void> {
  const pomPath = join(resolve(root), 'pom.xml')
  if (!existsSync(pomPath)) throw new Error('This project has no pom.xml')
  const pom = await readFile(pomPath, 'utf8')
  if (hasProfile(pom, PROFILE)) return
  const nl = pom.includes('\r\n') ? '\r\n' : '\n'
  const unit = pom.match(/\n([ \t]+)<modelVersion>/)?.[1] ?? '  '
  // Without the Camel Spring Boot BOM the starters need an explicit version.
  const usesBom = /<artifactId>camel-spring-boot-(bom|dependencies)<\/artifactId>/.test(pom)
  const literal = pom.match(/<artifactId>camel-spring-boot-starter<\/artifactId>\s*<version>([^<]+)<\/version>/)?.[1] ?? null
  const version = usesBom ? null : literal
  if (!usesBom && !version) throw new Error('Could not tell which Camel version this project uses. Add the camel-spring-boot-bom to pom.xml first.')

  let next: string
  const closeProfiles = pom.lastIndexOf('</profiles>')
  if (closeProfiles >= 0) {
    const lineStart = pom.lastIndexOf('\n', closeProfiles) + 1
    next = pom.slice(0, lineStart) + profilesXml(unit + unit, unit, nl, version) + nl + pom.slice(lineStart)
  } else {
    const closeProject = pom.lastIndexOf('</project>')
    if (closeProject < 0) throw new Error('pom.xml has no closing </project> tag')
    const block = [`${unit}<profiles>`, profilesXml(unit + unit, unit, nl, version), `${unit}</profiles>`].join(nl)
    next = pom.slice(0, closeProject).replace(/\s*$/, '') + nl + nl + block + nl + pom.slice(closeProject)
  }
  await writeFile(pomPath, next, 'utf8')
}

async function walk(dir: string, depth: number, visit: (file: string) => Promise<void>): Promise<void> {
  if (depth < 0) return
  let entries
  try {
    entries = await readdir(dir, { withFileTypes: true })
  } catch {
    return
  }
  for (const e of entries) {
    if (e.name.startsWith('.') && e.isDirectory()) continue
    const full = join(dir, e.name)
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name)) await walk(full, depth - 1, visit)
    } else if (e.isFile()) {
      await visit(full)
    }
  }
}

function firstTag(xml: string, tag: string): string | null {
  return xml.match(new RegExp(`<${tag}>\\s*([^<]+?)\\s*</${tag}>`))?.[1] ?? null
}

export async function scanProject(rootInput: string): Promise<ProjectInfo> {
  const root = resolve(rootInput)
  const info = await stat(root)
  if (!info.isDirectory()) throw new Error(`${root} is not a folder`)

  const pomPath = join(root, 'pom.xml')
  const hasPom = existsSync(pomPath)
  let runtimeTools = false
  let groupId: string | null = null
  let artifactId: string | null = null
  let camelVersion: string | null = null
  let springBootVersion: string | null = null
  let version: string | null = null
  if (hasPom) {
    const pom = await readFile(pomPath, 'utf8')
    runtimeTools = hasProfile(pom, PROFILE)
    const parent = pom.match(/<parent>[\s\S]*?<\/parent>/)?.[0] ?? ''
    const own = pom.replace(parent, '').replace(/<dependencyManagement>[\s\S]*?<\/dependencyManagement>/, '')
    const head = own.split(/<dependencies>/)[0]
    artifactId = firstTag(head, 'artifactId')
    groupId = firstTag(head, 'groupId') ?? firstTag(parent, 'groupId')
    version = firstTag(head.split(/<(properties|build|profiles|modules)>/)[0], 'version') ?? firstTag(parent, 'version')
    camelVersion =
      firstTag(pom, 'camel.version') ??
      firstTag(pom, 'camel-version') ??
      firstTag(pom, 'camel-spring-boot.version') ??
      pom.match(/<artifactId>camel-spring-boot-(?:bom|dependencies)<\/artifactId>\s*<version>([^<$]+)</)?.[1] ??
      null
    if (/spring-boot-starter-parent/.test(parent)) springBootVersion = firstTag(parent, 'version')
  }

  const routeFiles: RouteFileInfo[] = []
  const javaRoutes: RouteFileInfo[] = []
  const toInfo = (path: string): RouteFileInfo => ({ path, rel: toPosix(relative(root, path)), name: basename(path) })

  const config = await readConfig(root)
  const routeFormat: RouteFormat = config.routeFormat === 'java' ? 'java' : 'yaml'
  const javaPackage = config.javaPackage ?? `${(await basePackage(root)) ?? groupId ?? 'com.example'}.routes`
  const javaDir = `src/main/java/${javaPackage.replace(/\./g, '/')}`

  // Global variables live in Spring's own property files, one per environment (profile).
  const envFiles: { env: string; rel: string }[] = []
  for (const name of (await readdir(join(root, 'src', 'main', 'resources')).catch(() => [] as string[])).sort()) {
    const m = name.match(/^application(?:-([\w.-]+))?\.properties$/)
    if (m) envFiles.push({ env: m[1] ?? 'default', rel: `src/main/resources/${name}` })
  }

  const resources = join(root, 'src', 'main', 'resources')
  const yamlRoot = routeFormat === 'java' ? join(root, MODEL_DIR) : existsSync(resources) ? resources : root
  await walk(yamlRoot, 6, async (file) => {
    if (!/\.ya?ml$/i.test(file)) return
    if (/\.camel\.ya?ml$/i.test(file)) {
      routeFiles.push(toInfo(file))
      return
    }
    try {
      const head = (await readFile(file, 'utf8')).slice(0, 8192)
      if (ROUTE_ROOT_KEYS.test(head)) routeFiles.push(toInfo(file))
    } catch {
      /* unreadable file: ignore */
    }
  })

  const javaRoot = join(root, 'src', 'main', 'java')
  if (existsSync(javaRoot)) {
    await walk(javaRoot, 12, async (file) => {
      if (!file.endsWith('.java')) return
      try {
        const text = await readFile(file, 'utf8')
        // Classes Camel Studio generates are edited through their model, not listed as hand-written Java.
        if (JAVA_ROUTE.test(text) && !text.includes(GENERATED_MARK)) javaRoutes.push(toInfo(file))
      } catch {
        /* ignore */
      }
    })
  }

  const byRel = (a: RouteFileInfo, b: RouteFileInfo): number => a.rel.localeCompare(b.rel)
  routeFiles.sort(byRel)
  javaRoutes.sort(byRel)

  // Prefer the folder existing routes already live in; fall back to Camel's default scan location.
  let routesDir = YAML_DIR
  if (routeFormat === 'java') {
    routesDir = MODEL_DIR
  } else if (routeFiles.length > 0) {
    routesDir = routeFiles[0].rel.split('/').slice(0, -1).join('/')
  } else if (!existsSync(resources)) {
    routesDir = ''
  }

  return {
    root,
    name: artifactId ?? basename(root),
    hasPom,
    groupId,
    artifactId,
    camelVersion,
    springBootVersion,
    routesDir,
    routeFiles,
    javaRoutes,
    runtimeTools,
    routeFormat,
    javaPackage,
    javaDir,
    envFiles,
    version
  }
}

/** Sets the project's own <version> (a direct child of <project>), keeping the rest of pom.xml as it is. */
export async function setProjectVersion(root: string, version: string): Promise<ProjectInfo> {
  if (!/^[A-Za-z0-9][\w.+-]*$/.test(version)) throw new Error('A version is letters, digits, dots and dashes, like 1.4.0 or 1.4.0-SNAPSHOT')
  const pomPath = join(root, 'pom.xml')
  const pom = await readFile(pomPath, 'utf8')
  // Walk the tags and track depth: only a <version> at depth 1 belongs to the project itself.
  const tag = /<(\/?)([\w.-]+)[^>]*?(\/?)>|<!--[\s\S]*?-->|<\?[\s\S]*?\?>/g
  let depth = 0
  let artifactEnd = -1
  for (let m = tag.exec(pom); m; m = tag.exec(pom)) {
    if (!m[2]) continue
    if (m[1]) {
      depth--
      if (depth === 1 && m[2] === 'artifactId' && artifactEnd < 0) artifactEnd = m.index + m[0].length
      continue
    }
    if (m[3]) continue
    depth++
    if (depth === 2 && m[2] === 'version') {
      const close = pom.indexOf('</version>', m.index)
      await writeFile(pomPath, pom.slice(0, m.index + m[0].length) + version + pom.slice(close), 'utf8')
      return scanProject(root)
    }
  }
  if (artifactEnd < 0) throw new Error('pom.xml has no artifactId for the project')
  const indent = pom.slice(pom.lastIndexOf('\n', artifactEnd) + 1).match(/^\s*/)?.[0] ?? '  '
  await writeFile(pomPath, `${pom.slice(0, artifactEnd)}\n${indent}<version>${version}</version>${pom.slice(artifactEnd)}`, 'utf8')
  return scanProject(root)
}

/**
 * Java projects: removes generated classes whose design file no longer exists, so a deleted
 * route does not keep running. Hand-written classes (no Camel Studio header) are never touched.
 */
export async function pruneGenerated(rootInput: string, keep: string[]): Promise<string[]> {
  const project = await scanProject(rootInput)
  if (project.routeFormat !== 'java') return []
  const dir = join(project.root, project.javaDir)
  const removed: string[] = []
  for (const name of await readdir(dir).catch(() => [] as string[])) {
    if (!name.endsWith('.java') || keep.includes(name)) continue
    const text = await readFile(join(dir, name), 'utf8').catch(() => '')
    if (!text.includes(GENERATED_MARK)) continue
    await unlink(join(dir, name))
    removed.push(name)
  }
  return removed
}

/**
 * Switches a project between YAML routes and generated Java classes by moving the route files
 * between the classpath folder and the model folder. Generating (or removing) the classes for the
 * new format is done by the caller, which owns the generator.
 */
export async function setRouteFormat(rootInput: string, format: RouteFormat): Promise<ProjectInfo> {
  const before = await scanProject(rootInput)
  if (before.routeFormat === format) return before
  const targetDir = join(before.root, format === 'java' ? MODEL_DIR : YAML_DIR)
  await mkdir(targetDir, { recursive: true })
  for (const f of before.routeFiles) {
    const dest = join(targetDir, f.name)
    if (existsSync(dest)) throw new Error(`${f.name} already exists in ${format === 'java' ? MODEL_DIR : YAML_DIR}`)
    await rename(f.path, dest)
  }
  if (format === 'yaml') {
    // The YAML files run directly again: remove the classes generated from them.
    const dir = join(before.root, before.javaDir)
    for (const name of await readdir(dir).catch(() => [] as string[])) {
      if (!name.endsWith('.java')) continue
      const text = await readFile(join(dir, name), 'utf8').catch(() => '')
      if (text.includes(GENERATED_MARK)) await unlink(join(dir, name))
    }
  }
  await writeConfig(before.root, { ...(await readConfig(before.root)), routeFormat: format, javaPackage: before.javaPackage })
  return scanProject(before.root)
}

/** Throws unless `path` is inside `root`. Every file operation coming from the UI goes through this. */
export function assertInside(root: string, path: string): string {
  const full = resolve(path)
  const base = resolve(root)
  if (full !== base && !full.startsWith(base + sep)) throw new Error(`Path is outside the open project: ${path}`)
  return full
}

export async function createRouteFile(root: string, fileName: string, content: string): Promise<RouteFileInfo> {
  const project = await scanProject(root)
  const safe = fileName.replace(/[^A-Za-z0-9._-]/g, '-').replace(/\.camel\.ya?ml$|\.ya?ml$/i, '')
  if (!safe) throw new Error('File name is empty')
  const dir = join(project.root, project.routesDir)
  await mkdir(dir, { recursive: true })
  const path = assertInside(project.root, join(dir, `${safe}.camel.yaml`))
  if (existsSync(path)) throw new Error(`${safe}.camel.yaml already exists`)
  await writeFile(path, content, 'utf8')
  return { path, rel: toPosix(relative(project.root, path)), name: basename(path) }
}

