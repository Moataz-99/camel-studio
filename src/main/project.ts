/**
 * Points pom.xml at the Camel version the designer uses: the camel.version property and the
 * Spring Boot parent version it is built against. Only these two values change.
 */
export async function alignVersions(root: string, camel: string, springBoot: string | null): Promise<{ changed: string[] }> {
  const pomPath = join(resolve(root), 'pom.xml')
  let pom = await readFile(pomPath, 'utf8')
  const changed: string[] = []
  const prop = pom.match(/<camel\.version>([^<]+)<\/camel\.version>/)
  if (prop && prop[1] !== camel) {
    pom = pom.replace(prop[0], `<camel.version>${camel}</camel.version>`)
    changed.push(`Camel ${prop[1]} → ${camel}`)
  }
  const parent = pom.match(/<parent>[\s\S]*?<artifactId>spring-boot-starter-parent<\/artifactId>[\s\S]*?<version>([^<]+)<\/version>[\s\S]*?<\/parent>/)
  if (parent && springBoot && parent[1] !== springBoot) {
    pom = pom.replace(parent[0], parent[0].replace(`<version>${parent[1]}</version>`, `<version>${springBoot}</version>`))
    changed.push(`Spring Boot ${parent[1]} → ${springBoot}`)
  }
  if (!prop && !parent) throw new Error('pom.xml has neither a camel.version property nor a Spring Boot parent to change')
  if (changed.length) await writeFile(pomPath, pom, 'utf8')
  return { changed }
}
