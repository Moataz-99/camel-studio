const STARTER_GROUP = 'org.apache.camel.springboot'

/**
 * Adds the Camel Spring Boot starters the routes need (camel-kafka -> camel-kafka-starter).
 * Only ever appends; it never removes or reorders what the team wrote by hand.
 */
export async function syncDependencies(root: string, artifactIds: string[]): Promise<DependencySyncResult> {
  const pomPath = join(resolve(root), 'pom.xml')
  if (!existsSync(pomPath)) return { added: [], skipped: 'No pom.xml in this project' }
  const pom = await readFile(pomPath, 'utf8')
  if (!/camel-spring-boot/.test(pom)) {
    return { added: [], skipped: 'pom.xml does not use Camel Spring Boot; dependencies left untouched' }
  }

  // The team's own components are added with their exact coordinates; Camel ones as Spring Boot starters.
  const custom = new Map(getSettings().components.map((c) => [c.artifactId, c]))
  const starters = [...new Set(artifactIds.filter((a) => a && !custom.has(a)).map((a) => (a.endsWith('-starter') ? a : `${a}-starter`)))]
  const missing = starters.filter((s) => !new RegExp(`<artifactId>\\s*${s}\\s*</artifactId>`).test(pom))
  const missingCustom = [...new Set(artifactIds)].map((a) => custom.get(a)).filter((c): c is NonNullable<typeof c> => !!c && !new RegExp(`<artifactId>\\s*${c.artifactId}\\s*</artifactId>`).test(pom))
  if (missing.length === 0 && missingCustom.length === 0) return { added: [], skipped: null }

  // Find the project's own </dependencies>, not the one inside <dependencyManagement>.
  const mgmt = pom.match(/<dependencyManagement>[\s\S]*?<\/dependencyManagement>/)
  const mgmtStart = mgmt ? pom.indexOf(mgmt[0]) : -1
  const mgmtEnd = mgmt ? mgmtStart + mgmt[0].length : -1
  let insertAt = -1
  const closeTag = /<\/dependencies>/g
  for (let m = closeTag.exec(pom); m; m = closeTag.exec(pom)) {
    if (m.index >= mgmtStart && m.index < mgmtEnd) continue
    const before = pom.slice(0, m.index)
    if (before.lastIndexOf('<plugin>') > before.lastIndexOf('</plugin>')) continue
    insertAt = m.index
    break
  }
  if (insertAt < 0) return { added: [], skipped: 'Could not find a <dependencies> section in pom.xml' }

  const lineStart = pom.lastIndexOf('\n', insertAt) + 1
  const closeIndent = pom.slice(lineStart, insertAt).match(/^\s*/)?.[0] ?? ''
  const unit = pom.match(/\n(\s+)<modelVersion>/)?.[1] ?? '  '
  const i1 = closeIndent + unit
  const i2 = i1 + unit
  const nl = pom.includes('\r\n') ? '\r\n' : '\n'
  const block = [
    ...missing.map((s) => [`${i1}<dependency>`, `${i2}<groupId>${STARTER_GROUP}</groupId>`, `${i2}<artifactId>${s}</artifactId>`, `${i1}</dependency>`].join(nl)),
    ...missingCustom.map((c) =>
      [`${i1}<!-- ${c.title}: a team component (Camel Studio) -->`, `${i1}<dependency>`, `${i2}<groupId>${c.groupId}</groupId>`, `${i2}<artifactId>${c.artifactId}</artifactId>`, ...(c.version ? [`${i2}<version>${c.version}</version>`] : []), `${i1}</dependency>`].join(nl)
    )
  ].join(nl)

  await writeFile(pomPath, pom.slice(0, lineStart) + block + nl + pom.slice(lineStart), 'utf8')
  return { added: [...missing, ...missingCustom.map((c) => c.artifactId)], skipped: null }
}

