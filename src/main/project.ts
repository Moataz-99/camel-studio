import { mkdir, readdir, readFile, rename, stat, unlink, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { basename, join, relative, resolve, sep } from 'node:path'
import { getSettings } from './settings'
import type { DependencySyncResult, NewProjectOptions, ProjectInfo, RouteFileInfo, RouteFormat } from '@shared/types'

const SKIP_DIRS = new Set(['node_modules', 'target', 'build', 'dist', 'out', '.git', '.idea', '.mvn', '.gradle'])
const ROUTE_ROOT_KEYS = /^-\s+(route|from|rest|routeConfiguration|routeTemplate|beans|onException|intercept|restConfiguration)\s*:/m
const JAVA_ROUTE = /\bextends\s+(Endpoint)?RouteBuilder\b/

const toPosix = (p: string): string => p.split(sep).join('/')

// ---------------------------------------------------------- route format --

/** Java mode: the visual models live here, outside the classpath, so Camel only loads the generated classes. */
export const MODEL_DIR = 'src/main/camel-studio'
const YAML_DIR = 'src/main/resources/camel'
const CONFIG_FILE = join('.camel-studio', 'project.json')
/** First line of the header javagen.ts writes; used to recognise classes Camel Studio owns. */
const GENERATED_MARK = 'Generated by Camel Studio from'

interface ProjectConfig {
  routeFormat?: RouteFormat
  javaPackage?: string
}

async function readConfig(root: string): Promise<ProjectConfig> {
  try {
    return JSON.parse(await readFile(join(root, CONFIG_FILE), 'utf8')) as ProjectConfig
  } catch {
    return {}
  }
}

async function writeConfig(root: string, config: ProjectConfig): Promise<void> {
  await mkdir(join(root, '.camel-studio'), { recursive: true })
  await writeFile(join(root, CONFIG_FILE), `${JSON.stringify(config, null, 2)}\n`, 'utf8')
}

/** Package of the @SpringBootApplication class: generated routes must sit under it to be component-scanned. */
async function basePackage(root: string): Promise<string | null> {
  let found: string | null = null
  await walk(join(root, 'src', 'main', 'java'), 12, async (file) => {
    if (found || !file.endsWith('.java')) return
    const text = await readFile(file, 'utf8').catch(() => '')
    if (/@SpringBootApplication\b/.test(text)) found = text.match(/^\s*package\s+([\w.]+)\s*;/m)?.[1] ?? null
  })
  return found
}

